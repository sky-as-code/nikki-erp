func (this *EntitlementDomainServiceImpl) ManageEntitlementRoles(
	ctx corectx.Context, cmd itEnt.ManageEntitlementRolesCommand,
) (*itEnt.ManageEntitlementRolesResult, error) {
	result, err := corecrud.ManageM2m(ctx, corecrud.ManageM2mParam{
		Action:             "manage entitlement roles",
		DbRepoGetter:       this.entitlementRepo,
		DestSchemaName:     domain.RoleSchemaName,
		SrcId:              cmd.EntitlementId,
		SrcIdFieldForError: "entitlement_id",
		AssociatedIds:      cmd.Add,
		DisassociatedIds:   cmd.Remove,
	})
	if err != nil || result.ClientErrors.Count() > 0 || !result.HasData {
		return result, err
	}
	// Every role on either side of the change gains or loses this entitlement, so
	// each one's holders need recomputing.
	for _, roleId := range append(cmd.Add.ToSlice(), cmd.Remove.ToSlice()...) {
		if err := this.permRepo.RebuildUserPermissionsForRole(ctx, roleId); err != nil {
			return nil, err
		}
	}
	return result, nil
}

