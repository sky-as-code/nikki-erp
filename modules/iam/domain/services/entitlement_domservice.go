func (this *EntitlementDomainServiceImpl) SetEntitlementIsArchived(
	ctx corectx.Context, cmd itEnt.SetEntitlementIsArchivedCommand,
) (*itEnt.SetEntitlementIsArchivedResult, error) {
	result, err := corecrud.SetIsArchived(ctx, this.entitlementRepo, dyn.SetIsArchivedCommand(cmd))
	if err != nil || result.ClientErrors.Count() > 0 || !result.HasData {
		return result, err
	}
	// Archiving is a revocation and unarchiving is a grant; neither reaches the
	// cache on its own, because archived rows are filtered inside the rebuild
	// function rather than deleted by a cascade.
	if err := this.rebuildForEntitlementRole(ctx, cmd.Id); err != nil {
		return nil, err
	}
	return result, nil
}

func (this *EntitlementDomainServiceImpl) UpdateEntitlement(
	ctx corectx.Context, cmd itEnt.UpdateEntitlementCommand, options ...corecrud.ServiceUpdateOptions[*domain.Entitlement],
) (*itEnt.UpdateEntitlementResult, error) {
	opts := safe.GetOptional(options, corecrud.ServiceUpdateOptions[*domain.Entitlement]{})
	result, err := corecrud.Update(ctx, corecrud.UpdateParam[domain.Entitlement, *domain.Entitlement]{
		Action:                 "update entitlement",
		DbRepoGetter:           this.entitlementRepo,
		Data:                   cmd,
		AfterValidationSuccess: opts.AfterValidationSuccess,
	})
	if err != nil || result.ClientErrors.Count() > 0 || !result.HasData {
		return result, err
	}
	if entId := cmd.GetId(); entId != nil {
		if err := this.rebuildForEntitlementRole(ctx, *entId); err != nil {
			return nil, err
		}
	}
	return result, nil
}
