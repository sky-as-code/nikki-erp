func NewEntitlementDomainServiceImpl(
	entitlementRepo itEnt.EntitlementRepository,
	actionRepo itAct.ActionRepository,
	resourceRepo itRes.ResourceRepository,
	orgRepo itOrg.OrganizationRepository,
	orgUnitRepo itOrgUnit.OrgUnitRepository,
	permRepo itPerm.PermissionRepository,
	historyRepo itPerm.PermissionHistoryRepository,
	cqrsBus cqrs.CqrsBus,
) itEnt.EntitlementDomainService {
	return &EntitlementDomainServiceImpl{
		cqrsBus:         cqrsBus,
		entitlementRepo: entitlementRepo,
		actionRepo:      actionRepo,
		resourceRepo:    resourceRepo,
		// orgRepo was accepted by the constructor but never stored, so every
		// org-scoped entitlement crashed on a nil dereference in checkOrgExistence.
		orgRepo:     orgRepo,
		orgUnitRepo: orgUnitRepo,
		permRepo:    permRepo,
		auditor:         permissionAuditor{historyRepo: historyRepo},
	}
}

type EntitlementDomainServiceImpl struct {
	cqrsBus         cqrs.CqrsBus
	entitlementRepo itEnt.EntitlementRepository
	actionRepo      itAct.ActionRepository
	resourceRepo    itRes.ResourceRepository
	orgRepo         itOrg.OrganizationRepository
	orgUnitRepo     itOrgUnit.OrgUnitRepository
	permRepo        itPerm.PermissionRepository
	auditor         permissionAuditor
}

// rebuildForEntitlementRole refreshes the cached permissions of everyone holding
// the role that owns the entitlement.
//
// Called after every mutation that changes what an entitlement grants. Without it
// the cache fails in the unsafe direction: deletions cascade away immediately, but
// an addition never reaches the people who already hold the role.
func (this *EntitlementDomainServiceImpl) rebuildForEntitlementRole(ctx corectx.Context, entitlementId model.Id) error {
	roleId, err := this.roleIdOfEntitlement(ctx, entitlementId)
	if err != nil || roleId == nil {
		return err
	}
	return this.permRepo.RebuildUserPermissionsForRole(ctx, *roleId)
}

func (this *EntitlementDomainServiceImpl) roleIdOfEntitlement(
	ctx corectx.Context, entitlementId model.Id,
) (*model.Id, error) {
	resEnt, err := this.entitlementRepo.GetOne(ctx, dyn.RepoGetOneParam{
		Filter: dmodel.DynamicFields{domain.EntitlementFieldId: entitlementId},
		Fields: []string{domain.EntitlementFieldRoleId},
	})
	if err != nil {
		return nil, err
	}
	if !resEnt.HasData {
		return nil, nil
	}
	return resEnt.Data.GetRoleId(), nil
}

func (this *EntitlementDomainServiceImpl) CreateEntitlement(
	ctx corectx.Context, cmd itEnt.CreateEntitlementCommand, options ...corecrud.ServiceCreateOptions[*domain.Entitlement],
) (*itEnt.CreateEntitlementResult, error) {
	opts := safe.GetOptional(options, corecrud.ServiceCreateOptions[*domain.Entitlement]{})
	result, err := corecrud.Create(ctx, corecrud.CreateParam[domain.Entitlement, *domain.Entitlement]{
		Action:         "create entitlement",
		BaseRepoGetter: this.entitlementRepo,
		Data:           cmd,
		BeforeValidation: func(ctx corectx.Context, ent *domain.Entitlement, vErrs *ft.ClientErrors) (*domain.Entitlement, error) {
			return ent, this.validateScope(ctx, ent, vErrs)
		},
		// The expression is computed AFTER validation, not before. `expression` is
		// declared AutoGenerated, and validation blanks every auto-generated field
		// so its generator can fill it in - which would discard anything computed
		// in BeforeValidation and leave the column NULL on insert.
		AfterValidationSuccess: func(ctx corectx.Context, ent *domain.Entitlement) (*domain.Entitlement, error) {
			if err := this.calculateExpression(ctx, ent, ft.NewClientErrors()); err != nil {
				return ent, err
			}
			if opts.AfterValidationSuccess != nil {
				return opts.AfterValidationSuccess(ctx, ent)
			}
			return ent, nil
		},
	})
	if err != nil || result.ClientErrors.Count() > 0 || !result.HasData {
		return result, err
	}
	// A new entitlement has to reach the role's existing holders, not just the
	// next person assigned to it.
	if roleId := result.Data.GetRoleId(); roleId != nil {
		if err := this.permRepo.RebuildUserPermissionsForRole(ctx, *roleId); err != nil {
			return nil, err
		}
		if err := this.auditor.recordEntitlementTransition(
			ctx, domain.PermissionHistoryEffectGrant, domain.PermissionHistoryReasonEntAdded,
			roleId, result.Data.GetId(), result.Data.GetFieldData().GetString(domain.EntitlementFieldExpression),
		); err != nil {
			return nil, err
		}
	}
	return result, nil
}

// calculateExpression resolves the action and resource **codes** behind the ids the
// caller sent, then lets the entitlement build its expression from them.
//
// The runtime guard looks for expressions built from codes, so resolving them here
// is what makes an API-created entitlement enforceable at all (plan defect D1). A
// nil id means "all actions" / "all resources" and becomes the wildcard, so a
// missing id is not an error.
func (this *EntitlementDomainServiceImpl) calculateExpression(
	ctx corectx.Context, ent *domain.Entitlement, vErrs *ft.ClientErrors,
) error {
	actionCode, err := this.resolveActionCode(ctx, ent.GetActionId(), vErrs)
	if err != nil {
		return err
	}
	resourceCode, err := this.resolveResourceCode(ctx, ent.GetResourceId(), vErrs)
	if err != nil {
		return err
	}
	if vErrs.Count() > 0 {
		return nil
	}

	ent.CalculateExpression(actionCode, resourceCode)
	return nil
}

func (this *EntitlementDomainServiceImpl) resolveActionCode(
	ctx corectx.Context, actionId *model.Id, vErrs *ft.ClientErrors,
) (*string, error) {
	if actionId == nil {
		return nil, nil
	}
	resAction, err := this.actionRepo.GetOne(ctx, dyn.RepoGetOneParam{
		Filter: dmodel.DynamicFields{domain.ActionFieldId: *actionId},
		Fields: []string{domain.ActionFieldCode},
	})
	if err != nil {
		return nil, err
	}
	if !resAction.HasData {
		vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldActionId))
		return nil, nil
	}
	return resAction.Data.GetCode(), nil
}

func (this *EntitlementDomainServiceImpl) resolveResourceCode(
	ctx corectx.Context, resourceId *model.Id, vErrs *ft.ClientErrors,
) (*string, error) {
	if resourceId == nil {
		return nil, nil
	}
	resResource, err := this.resourceRepo.GetOne(ctx, dyn.RepoGetOneParam{
		Filter: dmodel.DynamicFields{domain.ResourceFieldId: *resourceId},
		Fields: []string{domain.ResourceFieldCode},
	})
	if err != nil {
		return nil, err
	}
	if !resResource.HasData {
		vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldResourceId))
		return nil, nil
	}
	return resResource.Data.GetCode(), nil
}

func (this *EntitlementDomainServiceImpl) validateScope(
	ctx corectx.Context, ent *domain.Entitlement, cErrsTotal *ft.ClientErrors,
) error {
	resourceId := ent.GetResourceId()
	if resourceId == nil {
		cErrsTotal.Append(*dmodel.NewMissingFieldErr(domain.EntitlementFieldResourceId))
		return nil
	}
	resource, err := this.fetchResourceForAction(ctx, resourceId, cErrsTotal)
	if err != nil {
		return err
	}
	if cErrsTotal.Count() > 0 || resource == nil {
		return nil
	}
	// A resource whose scope bounds or an entitlement whose scope is absent is a
	// client error, not a crash: every one of these was a nil dereference reported
	// to the caller as a 500.
	minScopePtr, maxScopePtr, entScopePtr := resource.GetMinScope(), resource.GetMaxScope(), ent.GetScope()
	if minScopePtr == nil || maxScopePtr == nil {
		cErrsTotal.Append(*ft.NewNotFoundError(domain.EntitlementFieldResourceId))
		return nil
	}
	if entScopePtr == nil {
		cErrsTotal.Append(*dmodel.NewMissingFieldErr(domain.EntitlementFieldScope))
		return nil
	}

	minScope := *minScopePtr
	maxScope := *maxScopePtr
	entScope := *entScopePtr
	orgId := ent.GetOrgId()
	orgUnitId := ent.GetOrgUnitId()

	cErrs, err := dyn.StartValidationFlowCopy(cErrsTotal).
		Step(func(cErrs *ft.ClientErrors) error {
			return this.checkOrgExistence(ctx, entScope, orgId, cErrs)
		}).
		Step(func(cErrs *ft.ClientErrors) error {
			return this.checkOrgUnitExistence(ctx, entScope, orgUnitId, cErrs)
		}).
		Step(func(cErrs *ft.ClientErrors) error {
			if !domain.IsResourceScopeInBounds(minScope, maxScope, entScope) {
				cErrs.Append(*ft.NewValidationError(
					domain.EntitlementFieldScope, "err_scope_out_of_bounds",
					"scope must be between the resource min_scope and max_scope (both inclusive)",
				))
			}
			return nil
		}).
		End()
	cErrsTotal.Concat(cErrs)

	return err
}

func (this *EntitlementDomainServiceImpl) checkOrgExistence(ctx corectx.Context, entScope c.ResourceScope, orgId *model.Id, vErrs *ft.ClientErrors) error {
	if entScope == c.ResourceScopeOrg && orgId == nil {
		vErrs.Append(*dmodel.NewMissingFieldErr(domain.EntitlementFieldOrgId))
		return nil
	}
	if entScope == c.ResourceScopeOrg && orgId != nil {
		org := domain.NewOrganization()
		org.SetId(orgId)
		existence, err := this.orgRepo.Exists(ctx, []domain.Organization{*org})
		if err != nil {
			return err
		}
		if len(existence.Data.Existing) == 0 {
			vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldOrgId))
			return nil
		}
	}
	return nil
}

func (this *EntitlementDomainServiceImpl) checkOrgUnitExistence(ctx corectx.Context, entScope c.ResourceScope, orgUnitId *model.Id, vErrs *ft.ClientErrors) error {
	if entScope == c.ResourceScopeOrgUnit && orgUnitId == nil {
		vErrs.Append(*dmodel.NewMissingFieldErr(domain.EntitlementFieldOrgUnitId))
		return nil
	}
	if entScope == c.ResourceScopeOrgUnit && orgUnitId != nil {
		orgUnit := domain.NewOrganizationalUnit()
		orgUnit.SetId(orgUnitId)
		existence, err := this.orgUnitRepo.Exists(ctx, []domain.OrganizationalUnit{*orgUnit})
		if err != nil {
			return err
		}
		if len(existence.Data.Existing) == 0 {
			vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldOrgUnitId))
			return nil
		}
	}
	return nil
}

func (this *EntitlementDomainServiceImpl) fetchResourceForAction(
	ctx corectx.Context, resourceId *model.Id, vErrs *ft.ClientErrors,
) (*domain.Resource, error) {

	resRes, err := this.resourceRepo.GetOne(ctx, dyn.RepoGetOneParam{
		Filter: dmodel.DynamicFields{
			domain.ResourceFieldId: *resourceId,
		},
		// min_scope and max_scope are what the caller actually validates against;
		// selecting only the actions edge left them nil, so the scope-bounds check
		// had nothing to compare and every create failed.
		Fields: []string{
			domain.ResourceFieldMinScope,
			domain.ResourceFieldMaxScope,
			fmt.Sprintf("%s.%s", domain.ResourceEdgeActions, domain.ActionFieldId),
		},
	})
	if err != nil {
		return nil, err
	}
	if !resRes.HasData {
		vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldResourceId))
		return nil, nil
	}
	if resRes.Data.GetActions() == nil {
		vErrs.Append(*ft.NewNotFoundError(domain.EntitlementFieldActionId))
		return nil, nil
	}
	r := resRes.Data
	return &r, nil
}

func (this *EntitlementDomainServiceImpl) DeleteEntitlement(
	ctx corectx.Context, cmd itEnt.DeleteEntitlementCommand, options ...corecrud.ServiceDeleteOptions,
) (*itEnt.DeleteEntitlementResult, error) {
	opts := safe.GetOptional(options, corecrud.ServiceDeleteOptions{})
	// Read the owning role before the row goes away - afterwards there is nothing
	// left to resolve it from. The cascade removes this entitlement's cached rows,
	// but holders of the role still need the rest of their rows recomputed.
	roleId, err := this.roleIdOfEntitlement(ctx, cmd.Id)
	if err != nil {
		return nil, err
	}

	result, err := corecrud.DeleteOne(ctx, corecrud.DeleteOneParam{
		Action:                 "delete entitlement",
		DbRepoGetter:           this.entitlementRepo,
		Cmd:                    dyn.DeleteOneCommand(cmd),
		AfterValidationSuccess: opts.AfterValidationSuccess,
	})
	if err != nil || result.ClientErrors.Count() > 0 || !result.HasData {
		return result, err
	}
	if roleId != nil {
		if err := this.permRepo.RebuildUserPermissionsForRole(ctx, *roleId); err != nil {
			return nil, err
		}
		entId := cmd.Id
		if err := this.auditor.recordEntitlementTransition(
			ctx, domain.PermissionHistoryEffectRevoke, domain.PermissionHistoryReasonEntDeleted,
			roleId, &entId, nil,
		); err != nil {
			return nil, err
		}
	}
	return result, nil
}

