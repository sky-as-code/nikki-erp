func (this Entitlement) GetScope() *c.ResourceScope {
	s := this.GetFieldData().GetString(EntitlementFieldScope)
	if s == nil {
		return nil
	}
	v := c.ResourceScope(*s)
	return &v
}

func (this *Entitlement) SetScope(v *c.ResourceScope) {
	if v == nil {
		this.GetFieldData().SetString(EntitlementFieldScope, nil)
		return
	}
	s := string(*v)
	this.GetFieldData().SetString(EntitlementFieldScope, &s)
}

