// importPlan is the mapping resolved against the schema and the file header: for every mapped
// column, which file column index feeds which field, and whether the field is an edge whose
// cell holds a label to resolve rather than a value to convert.
type importPlan struct {
	schema   *dmodel.ModelSchema
	language model.LanguageCode
	columns  []plannedColumn
}

type plannedColumn struct {
	index    int
	field    *dmodel.ModelField
	relation *dmodel.ModelRelation
}

// planImport validates the mapping and binds it to the header. Every problem is a client
// error, because the caller can fix it by changing the mapping.
func planImport(schema *dmodel.ModelSchema, headers []string, mapping ImportMapping) (*importPlan, *ft.ClientErrors) {
	cErrs := ft.NewClientErrors()
	plan := &importPlan{schema: schema, language: importLanguage(mapping)}
	seenTargets := map[string]bool{}
	headerIndex := indexHeaders(headers)

	for _, column := range mapping.Columns {
		field, ok := schema.Field(column.Target)
		if !ok || !importTargetEligible(schema, field) {
			cErrs.Append(*ft.NewValidationError(column.Target, ErrImportMappingUnknown,
				"the target is not an importable field", map[string]any{"field": column.Target}))
			continue
		}
		if seenTargets[column.Target] {
			cErrs.Append(*ft.NewValidationError(column.Target, ErrImportMappingDuplicate,
				"the target is mapped twice", map[string]any{"field": column.Target}))
			continue
		}
		seenTargets[column.Target] = true

		index, ok := headerIndex.lookup(column.Source)
		if !ok {
			cErrs.Append(*ft.NewValidationError(column.Target, ErrImportHeaderNotFound,
				"the file has no such column", map[string]any{"header": column.Source}))
			continue
		}
		plan.columns = append(plan.columns, plannedColumn{
			index:    index,
			field:    field,
			relation: edgeRelationOf(schema, column.Target),
		})
	}

	if missing := unmappedMandatory(schema, seenTargets); len(missing) > 0 {
		cErrs.Append(*ft.NewAnonymousValidationError(ErrImportMandatoryUnmapped,
			"every mandatory field needs a file column", map[string]any{"fields": missing}))
	}
	if cErrs.Count() > 0 {
		return nil, cErrs
	}
	return plan, nil
}

func importLanguage(mapping ImportMapping) model.LanguageCode {
	if strings.TrimSpace(mapping.LanguageCode) == "" {
		return model.LanguageCode(DefaultImportLanguage)
	}
	return model.LanguageCode(strings.TrimSpace(mapping.LanguageCode))
}

// headerIndex matches a mapping source to a file column: exact first, then case-insensitive,
// both after the whitespace normalisation the tabular reader already applied.
type headerIndex struct {
	exact  map[string]int
	folded map[string]int
}

func indexHeaders(headers []string) headerIndex {
	index := headerIndex{exact: map[string]int{}, folded: map[string]int{}}
	for i, header := range headers {
		if header == "" {
			continue
		}
		if _, dup := index.exact[header]; !dup {
			index.exact[header] = i
		}
		folded := strings.ToLower(header)
		if _, dup := index.folded[folded]; !dup {
			index.folded[folded] = i
		}
	}
	return index
}

func (this headerIndex) lookup(source string) (int, bool) {
	normalized := strings.Join(strings.Fields(source), " ")
	if i, ok := this.exact[normalized]; ok {
		return i, true
	}
	i, ok := this.folded[strings.ToLower(normalized)]
	return i, ok
}

// importTargetEligible says whether a field may be fed from a file: anything the server owns
// (keys, versioning, tenancy, generated values, derived values) is out; org_id is out because
// the request resolves it once for every row.
func importTargetEligible(schema *dmodel.ModelSchema, field *dmodel.ModelField) bool {
	if field == nil || field.IsAutoGenerated() || field.IsVirtual() {
		return false
	}
	name := field.Name()
	if name == basemodel.FieldOrgId || schema.IsPrimaryKey(name) || schema.IsTenantKey(name) {
		return false
	}
	return !field.IsVersioningKey()
}

// importMandatoryFields lists the targets a mapping must cover: required-for-create fields
// with no default, plus external_id wherever the schema declares it (requirement: it is
// always mandatory for import so every imported row can be recognised again).
func importMandatoryFields(schema *dmodel.ModelSchema) []string {
	mandatory := make([]string, 0)
	for _, field := range schema.Columns() {
		if !importTargetEligible(schema, field) {
			continue
		}
		name := field.Name()
		if name == FieldExternalId {
			mandatory = append(mandatory, name)
			continue
		}
		if field.IsRequiredForCreate() && !hasDefault(field) {
			mandatory = append(mandatory, name)
		}
	}
	return mandatory
}

func hasDefault(field *dmodel.ModelField) bool {
	if def := field.Default(); def != nil && !def.IsEmpty() {
		return true
	}
	return field.DefaultFn() != nil
}

func unmappedMandatory(schema *dmodel.ModelSchema, mapped map[string]bool) []string {
	missing := make([]string, 0)
	for _, name := range importMandatoryFields(schema) {
		if !mapped[name] {
			missing = append(missing, name)
		}
	}
	return missing
}

// edgeRelationOf returns the outgoing single-valued relation whose foreign key is fieldName,
// which is what makes a mapped column a reference column.
func edgeRelationOf(schema *dmodel.ModelSchema, fieldName string) *dmodel.ModelRelation {
	for _, relation := range schema.ToRelations() {
		if relation.IsInverse || relation.SrcField != fieldName {
			continue
		}
		if relation.RelationType == dmodel.RelationTypeManyToOne || relation.RelationType == dmodel.RelationTypeOneToOne {
			found := relation
			return &found
		}
	}
	return nil
}

// convertRows turns file rows into records. Every cell is typed against its field; an edge
// cell is kept as the raw label for the reference resolver. A row with any bad cell is
// rejected whole, so a half-typed record never reaches validation.
func (this *importPlan) convertRows(rows [][]string) ([]BulkRow, []RowError) {
	records := make([]BulkRow, 0, len(rows))
	rowErrors := make([]RowError, 0)
	for i, row := range rows {
		number := i + 1
		fields, rowErr := this.convertRow(number, row)
		if rowErr != nil {
			rowErrors = append(rowErrors, *rowErr)
			continue
		}
		records = append(records, BulkRow{Number: number, Fields: fields})
	}
	return records, rowErrors
}

func (this *importPlan) convertRow(number int, row []string) (dmodel.DynamicFields, *RowError) {
	fields := make(dmodel.DynamicFields, len(this.columns))
	for _, column := range this.columns {
		cell := ""
		if column.index < len(row) {
			cell = strings.TrimSpace(row[column.index])
		}
		if cell == "" {
			continue
		}
		if column.relation != nil {
			fields[column.field.Name()] = cell
			continue
		}
		value, ok := this.convertCell(column.field, cell)
		if !ok {
			return nil, &RowError{
				Row:    number,
				Field:  column.field.Name(),
				Code:   ErrRowCellInvalid,
				Params: map[string]any{"value": cell, "data_type": column.field.DataType().String()},
			}
		}
		fields[column.field.Name()] = value
	}
	return fields, nil
}

// convertCell types one cell through the field's own data type, the same conversion a JSON
// body gets on create. A multilingual field wraps the text under the mapping language.
func (this *importPlan) convertCell(field *dmodel.ModelField, cell string) (any, bool) {
	dataType := field.DataType()
	if dataType.String() == dmodel.FieldDataTypeNameLangJson {
		return model.LangJson{this.language: cell}, true
	}
	converted, err := dataType.TryConvert(cell, dataType.Options())
	if err != nil || converted.IsEmpty() {
		return nil, false
	}
	return *converted.Get(), true
}
