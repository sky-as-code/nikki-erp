// newImportSchemas declares a product-like owner with an edge to a category, registered and
// finalized so ToRelations carries the resolved relation the planner reads.
func newImportSchemas(t *testing.T) (owner *dmodel.ModelSchema, category *dmodel.ModelSchema) {
	t.Helper()
	category = dmodel.DefineModel("cmp_imp_category").
		ShouldBuildDb().
		RecordLabelField("name").
		Field(dmodel.DefineField().Name("id").DataType(dmodel.FieldDataTypeUlid()).PrimaryKey().IsAutoGenerated(true)).
		Field(dmodel.DefineField().Name(basemodel.FieldOrgId).DataType(dmodel.FieldDataTypeString(0, 50))).
		Field(dmodel.DefineField().Name("name").DataType(dmodel.FieldDataTypeString(1, 200)).IsRequiredForCreate(true)).
		Build()
	owner = dmodel.DefineModel("cmp_imp_product").
		ShouldBuildDb().
		Field(dmodel.DefineField().Name("id").DataType(dmodel.FieldDataTypeUlid()).PrimaryKey().IsAutoGenerated(true)).
		Field(dmodel.DefineField().Name(basemodel.FieldOrgId).DataType(dmodel.FieldDataTypeString(0, 50)).IsRequiredForCreate(true)).
		Field(dmodel.DefineField().Name("name").DataType(dmodel.FieldDataTypeString(1, 200)).IsRequiredForCreate(true)).
		Field(dmodel.DefineField().Name("qty").DataType(dmodel.FieldDataTypeInt32(0, 1000))).
		Field(dmodel.DefineField().Name("price").DataType(dmodel.FieldDataTypeDecimal("0", "999999", 2))).
		Field(dmodel.DefineField().Name("active").DataType(dmodel.FieldDataTypeBoolean())).
		Field(dmodel.DefineField().Name("title").DataType(dmodel.FieldDataTypeLangJson(0, 200))).
		Field(dmodel.DefineField().Name("category_id").DataType(dmodel.FieldDataTypeUlid())).
		Field(dmodel.DefineField().Name(FieldSourceSystem).DataType(dmodel.FieldDataTypeString(0, 50)).
			IsRequiredForCreate(true).Default("manual")).
		Field(dmodel.DefineField().Name(FieldExternalId).DataType(dmodel.FieldDataTypeString(0, 100))).
		EdgeTo(dmodel.Edge("category").ManyToOne("cmp_imp_category", dmodel.DynamicFields{"category_id": "id"})).
		Build()

	reg := dmodel.NewSchemaRegistry()
	require.NoError(t, reg.Register(category))
	require.NoError(t, reg.Register(owner))
	require.NoError(t, reg.FinalizeRelations())
	return owner, category
}

func fullMapping() ImportMapping {
	return ImportMapping{
		LanguageCode: "vi-VN",
		Columns: []ColumnMapping{
			{Source: "ID", Target: FieldExternalId},
			{Source: "Tên", Target: "name"},
			{Source: "SL", Target: "qty"},
			{Source: "Giá", Target: "price"},
			{Source: "Kích hoạt", Target: "active"},
			{Source: "Tiêu đề", Target: "title"},
			{Source: "Phân loại", Target: "category_id"},
		},
	}
}

var fullHeaders = []string{"ID", "Tên", "SL", "Giá", "Kích hoạt", "Tiêu đề", "Phân loại"}

func TestImportMandatoryFieldsAreRequiredWithoutDefaultPlusExternalId(t *testing.T) {
	owner, _ := newImportSchemas(t)

	assert.ElementsMatch(t, []string{"name", FieldExternalId}, importMandatoryFields(owner))
}

func TestImportTargetEligibilityExcludesServerOwnedFields(t *testing.T) {
	owner, _ := newImportSchemas(t)

	for name, want := range map[string]bool{
		"id": false, basemodel.FieldOrgId: false, "name": true, "category_id": true, "category": false,
	} {
		field, _ := owner.Field(name)
		assert.Equal(t, want, importTargetEligible(owner, field), name)
	}
}

func TestPlanImportBindsColumnsAndDetectsEdges(t *testing.T) {
	owner, _ := newImportSchemas(t)

	plan, cErrs := planImport(owner, fullHeaders, fullMapping())

	require.Nil(t, cErrs)
	require.Len(t, plan.columns, 7)
	assert.Equal(t, model.LanguageCode("vi-VN"), plan.language)
	last := plan.columns[6]
	assert.Equal(t, 6, last.index)
	require.NotNil(t, last.relation)
	assert.Equal(t, "cmp_imp_category", last.relation.DestSchemaName)
	assert.Nil(t, plan.columns[1].relation)
}

func TestPlanImportMatchesHeadersCaseInsensitively(t *testing.T) {
	owner, _ := newImportSchemas(t)
	mapping := ImportMapping{Columns: []ColumnMapping{
		{Source: " tên ", Target: "name"}, {Source: "id", Target: FieldExternalId},
	}}

	plan, cErrs := planImport(owner, []string{"ID", "Tên"}, mapping)

	require.Nil(t, cErrs)
	assert.Equal(t, 1, plan.columns[0].index)
	assert.Equal(t, model.LanguageCode(DefaultImportLanguage), plan.language)
}

func TestPlanImportReportsEveryMappingProblem(t *testing.T) {
	owner, _ := newImportSchemas(t)
	mapping := ImportMapping{Columns: []ColumnMapping{
		{Source: "Tên", Target: "name"},
		{Source: "Tên", Target: "name"},
		{Source: "X", Target: "nope"},
		{Source: "X", Target: "id"},
		{Source: "Missing", Target: "qty"},
	}}

	plan, cErrs := planImport(owner, []string{"Tên"}, mapping)

	assert.Nil(t, plan)
	require.NotNil(t, cErrs)
	codes := map[string]int{}
	for _, item := range *cErrs {
		codes[item.Key]++
	}
	assert.Equal(t, map[string]int{
		ErrImportMappingDuplicate:  1,
		ErrImportMappingUnknown:    2,
		ErrImportHeaderNotFound:    1,
		ErrImportMandatoryUnmapped: 1,
	}, codes)
	for _, item := range *cErrs {
		if item.Key == ErrImportMandatoryUnmapped {
			assert.Equal(t, []string{FieldExternalId}, item.Vars["fields"])
		}
	}
}

func TestConvertRowsTypesCellsAndKeepsEdgeLabels(t *testing.T) {
	owner, _ := newImportSchemas(t)
	plan, cErrs := planImport(owner, fullHeaders, fullMapping())
	require.Nil(t, cErrs)

	records, rowErrors := plan.convertRows([][]string{
		{"E1", "Coke", "12", "12000.5", "true", "Nước ngọt", "Beverage"},
		{"E2", "Pepsi", "", "", "", "", ""},
	})

	require.Empty(t, rowErrors)
	require.Len(t, records, 2)
	first := records[0].Fields
	assert.Equal(t, "E1", first[FieldExternalId])
	assert.Equal(t, int32(12), first["qty"])
	assert.True(t, decimal.NewFromFloat(12000.5).Equal(first["price"].(decimal.Decimal)))
	assert.Equal(t, true, first["active"])
	assert.Equal(t, model.LangJson{"vi-VN": "Nước ngọt"}, first["title"])
	assert.Equal(t, "Beverage", first["category_id"], "an edge cell stays a label for the resolver")
	assert.Equal(t, dmodel.DynamicFields{FieldExternalId: "E2", "name": "Pepsi"}, records[1].Fields, "empty cells are absent")
}

func TestConvertRowsRejectsTheWholeRowOnABadCell(t *testing.T) {
	owner, _ := newImportSchemas(t)
	plan, cErrs := planImport(owner, fullHeaders, fullMapping())
	require.Nil(t, cErrs)

	records, rowErrors := plan.convertRows([][]string{
		{"E1", "Coke", "twelve", "1", "true", "", ""},
		{"E2", "Pepsi", "1", "1", "yes", "", ""},
	})

	require.Len(t, records, 1)
	assert.Equal(t, 2, records[0].Number)
	require.Len(t, rowErrors, 1)
	assert.Equal(t, RowError{Row: 1, Field: "qty", Code: ErrRowCellInvalid,
		Params: map[string]any{"value": "twelve", "data_type": "int32"}}, rowErrors[0])
}
