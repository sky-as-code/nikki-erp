package models

import (
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	dmodel "github.com/sky-as-code/nikki-erp/common/dynamicmodel/model"
)

// The number belongs to the issue action (SEQ-FB-004): the schema itself drops whatever a client
// sends, on create and on edit, so no create or update path can plant a number the sequence never
// issued. The issue action writes it through the repository, which this validation does not guard.
func TestAClientInvoiceNumberIsIgnored(t *testing.T) {
	requireBaseSchemasRegistered(t)
	schema := InvoiceSchemaBuilder().Build()
	require.True(t, requireField(t, schema, InvoiceFieldNumber).IsAutoGenerated())

	created, _ := schema.Validate(dmodel.DynamicFields{InvoiceFieldNumber: "INV-2026-999999"})
	assert.Nil(t, created[InvoiceFieldNumber], "a client number on create is replaced by none")

	edited, _ := schema.Validate(dmodel.DynamicFields{InvoiceFieldNumber: "INV-2026-999999"}, true)
	assert.NotContains(t, edited, InvoiceFieldNumber, "a client number on edit is dropped")
}
