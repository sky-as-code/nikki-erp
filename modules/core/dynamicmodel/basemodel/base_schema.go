package basemodel

import (
	dmodel "github.com/sky-as-code/nikki-erp/common/dynamicmodel/model"
	"github.com/sky-as-code/nikki-erp/common/model"
)

const (
	FieldAssociations = "add"
	FieldDesociations = "remove"
	FieldId           = "id"
	FieldCreatedAt    = "created_at"
	FieldFields       = "fields"
	FieldIsArchived   = "is_archived"
	FieldOrgId        = "org_id"
	FieldGraph        = "graph"
	FieldPage         = "page"
	FieldSize         = "size"
	FieldSearchName   = "search_name"
	FieldUpdatedAt    = "updated_at"
	FieldEtag         = "etag"
)

func DefineFieldId(fieldName string) *dmodel.FieldBuilder {
	return dmodel.DefineField().
		Name(fieldName).
		DataType(dmodel.FieldDataTypeUlid())
}

func DefineFieldIdArr(fieldName string) *dmodel.FieldBuilder {
	return dmodel.DefineField().
		Name(fieldName).
		DataType(dmodel.FieldDataTypeUlid().ArrayType())
}

func ArchivableModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.archivable_model").
		Field(
			dmodel.DefineField().
				Name(FieldIsArchived).
				Label(model.NewLangJsonRefSf("fields.%s", FieldIsArchived)).
				DataType(dmodel.FieldDataTypeBoolean()).
				RequiredForCreate().
				Default(false).
				AutoGenerated(),
		)
}

func AuditableModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.auditable_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedAt).
				Label(model.NewLangJsonRefSf("fields.%s", FieldCreatedAt)).
				DataType(dmodel.FieldDataTypeDateTime()).
				RequiredForCreate().
				UseTypeDefault().
				AutoGenerated(),
		).
		Field(
			dmodel.DefineField().
				Name(FieldUpdatedAt).
				Label(model.NewLangJsonRefSf("fields.%s", FieldUpdatedAt)).
				DataType(dmodel.FieldDataTypeDateTime()).
				AutoGenerated(),
		)
}

func AuditableReadonlyModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.auditable_readonly_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedAt).
				Label(model.NewLangJsonRefSf("fields.%s", FieldCreatedAt)).
				DataType(dmodel.FieldDataTypeDateTime()).
				RequiredForCreate().
				UseTypeDefault().
				AutoGenerated(),
		)
}

func BaseModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.base_model").
		Field(
			DefineFieldId(FieldId).
				Label(model.NewLangJsonRefSf("fields.%s", FieldId)).
				UseTypeDefault().
				PrimaryKey(),
		).
		ExtendBase()
}

func OrgIdModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.org_base_model").
		Field(
			DefineFieldId(FieldOrgId).
				Label(model.NewLangJsonRefSf("fields.%s", FieldOrgId)).
				RequiredForCreate(),
		)
}

func VersionedModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.versioned_model").
		Field(
			dmodel.DefineField().
				Name(FieldEtag).
				Label(model.NewLangJsonRefSf("fields.%s", FieldEtag)).
				DataType(dmodel.FieldDataTypeEtag()).
				VersioningKey().
				UseTypeDefault(),
		)
}
