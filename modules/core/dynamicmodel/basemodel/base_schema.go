package basemodel

import (
	"context"

	dmodel "github.com/sky-as-code/nikki-erp/common/dynamicmodel/model"
	"github.com/sky-as-code/nikki-erp/common/model"
	coreCtx "github.com/sky-as-code/nikki-erp/modules/core/context"
)

const (
	FieldAssociations = "add"
	FieldDesociations = "remove"
	FieldId           = "id"
	FieldCreatedAt    = "created_at"
	FieldFields       = "fields"
	FieldIsArchived   = "is_archived"
	FieldOrgId        = "org_id"
	FieldGraph        = "graph"
	FieldPage         = "page"
	FieldSize         = "size"
	FieldSearchName   = "search_name"
	FieldUpdatedAt    = "updated_at"
	FieldEtag         = "etag"
	FieldCreatedBy    = "created_by"
	FieldUpdatedBy    = "updated_by"
)

func DefineFieldId(fieldName string) *dmodel.FieldBuilder {
	return dmodel.DefineField().
		Name(fieldName).
		DataType(dmodel.FieldDataTypeUlid())
}

func DefineFieldIdArr(fieldName string) *dmodel.FieldBuilder {
	return dmodel.DefineField().
		Name(fieldName).
		DataType(dmodel.FieldDataTypeUlid().ArrayType())
}

func ArchivableModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.archivable_model").
		Field(
			dmodel.DefineField().
				Name(FieldIsArchived).
				DataType(dmodel.FieldDataTypeBoolean()).
				RequiredForCreate().
				Default(false).
				AutoGenerated(),
		)
}

func AuditableModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.auditable_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedAt).
				Label(model.LangJson{model.LanguageCodeEnUs: "Created at"}).
				DataType(dmodel.FieldDataTypeDateTime()).
				RequiredForCreate().
				UseTypeDefault().
				AutoGenerated(),
		).
		Field(
			dmodel.DefineField().
				Name(FieldUpdatedAt).
				Label(model.LangJson{model.LanguageCodeEnUs: "Updated at"}).
				DataType(dmodel.FieldDataTypeDateTime()).
				AutoGenerated(),
		)
}

func AuditableReadonlyModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.auditable_readonly_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedAt).
				Label(model.LangJson{model.LanguageCodeEnUs: "Created at"}).
				DataType(dmodel.FieldDataTypeDateTime()).
				RequiredForCreate().
				UseTypeDefault().
				AutoGenerated(),
		)
}

func injectCreatedBy(ctx context.Context, forEdit bool) any {
	if forEdit {
		return nil
	}
	reqCtx, ok := ctx.(coreCtx.Context)
	if !ok {
		return nil
	}
	userId := reqCtx.GetPermissions().UserId
	if userId == "" {
		return nil
	}
	return userId
}

func injectUpdatedBy(ctx context.Context, _ bool) any {
	reqCtx, ok := ctx.(coreCtx.Context)
	if !ok {
		return nil
	}
	userId := reqCtx.GetPermissions().UserId
	if userId == "" {
		return nil
	}
	return userId
}

func TraceableModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.traceable_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedBy).
				DataType(dmodel.FieldDataTypeUlid()).
				ServiceInjected(injectCreatedBy),
		).
		Field(
			dmodel.DefineField().
				Name(FieldUpdatedBy).
				DataType(dmodel.FieldDataTypeUlid()).
				ServiceInjected(injectUpdatedBy),
		)
}

func TraceableReadonlyModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.traceable_readonly_model").
		Field(
			dmodel.DefineField().
				Name(FieldCreatedBy).
				DataType(dmodel.FieldDataTypeUlid()).
				ServiceInjected(injectCreatedBy),
		)
}

func BaseModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.base_model").
		Field(
			DefineFieldId(FieldId).
				Label(model.LangJson{model.LanguageCodeEnUs: "ID"}).
				UseTypeDefault().
				PrimaryKey(),
		).
		ExtendBase()
}

func OrgIdModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.org_base_model").
		Field(
			DefineFieldId(FieldOrgId).
				Label(model.LangJson{model.LanguageCodeEnUs: "Organization ID"}).
				RequiredForCreate(),
		)
}

func VersionedModelSchemaBuilder() *dmodel.ModelSchemaBuilder {
	return dmodel.DefineModel("core.basemodel.versioned_model").
		Field(
			dmodel.DefineField().
				Name(FieldEtag).
				DataType(dmodel.FieldDataTypeEtag()).
				VersioningKey().
				UseTypeDefault(),
		)
}
