// modelJsonDto mirrors the top-level shape declared in common/dynamicmodel/json/model_schema.json.
type modelJsonDto struct {
	Name                string `json:"name"`
	Label               any    `json:"label"`
	Description         any    `json:"description"`
	TableName           string `json:"table_name"`
	ShouldBuildDb       bool   `json:"should_build_db"`
	RecordLabelField    string `json:"record_label_field"`
	RecordSubLabelField string `json:"record_sub_label_field"`

	ExtendBefore []string `json:"extend_before"`
	ExtendAfter  []string `json:"extend_after"`

	Fields []fieldJsonDto `json:"fields"`

	CompositeUniques        []compositeUniqueDto `json:"composite_uniques"`
	PartialUniques          []partialUniqueDto   `json:"partial_uniques"`
	SearchIndexes           []searchIndexDto     `json:"search_indexes"`
	ExclusiveRequiredFields [][]string           `json:"exclusive_required_fields"`

	EdgesTo   []edgeJsonDto `json:"edges_to"`
	EdgesFrom []edgeJsonDto `json:"edges_from"`
}

type fieldJsonDto struct {
	Name        string `json:"name"`
	Label       any    `json:"label"`
	Description any    `json:"description"`
	Placeholder any    `json:"placeholder"`
	DataType    any    `json:"data_type"`

	RequiredAlways    bool   `json:"required_always"`
	RequiredForCreate bool   `json:"required_for_create"`
	RequiredForUpdate bool   `json:"required_for_update"`
	RequiredWith      string `json:"required_with"`

	NoUpdate      bool `json:"no_update"`
	Unique        bool `json:"unique"`
	AutoGenerated bool `json:"auto_generated"`
	TenantKey     bool `json:"tenant_key"`
	VersioningKey bool `json:"versioning_key"`
	PrimaryKey    any  `json:"primary_key"`

	DefaultValue   any  `json:"default_value"`
	UseTypeDefault bool `json:"use_type_default"`

	// Kept raw: the computed package owns the block's shape, and decoding it here would require
	// importing that package, which imports this one. See computed_hooks.go.
	Computed json.RawMessage `json:"computed"`

	Rules []ruleJsonDto `json:"rules"`
}

type ruleJsonDto struct {
	Name string `json:"name"`
	Min  int    `json:"min"`
	Max  int    `json:"max"`
}

type compositeUniqueDto struct {
	IndexName string   `json:"index_name"`
	Fields    []string `json:"fields"`
}

type partialUniqueDto struct {
	IndexName     string   `json:"index_name"`
	NotNullFields []string `json:"not_null_fields"`
	NullableField string   `json:"nullable_field"`
}

type searchIndexDto struct {
	IndexName string   `json:"index_name"`
	Fields    []string `json:"fields"`
}

type edgeJsonDto struct {
	Edge  string `json:"edge"`
	Label any    `json:"label"`
	Type  string `json:"type"`

	DestSchema string            `json:"dest_schema"`
	KeyMap     map[string]string `json:"key_map"`

	PeerSchema     string `json:"peer_schema"`
	ThroughSchema  string `json:"through_schema"`
	SrcFieldPrefix string `json:"src_field_prefix"`

	Existing *existingEdgeDto `json:"existing"`

	OnDelete string `json:"on_delete"`
	OnUpdate string `json:"on_update"`
}

type existingEdgeDto struct {
	SrcSchema string `json:"src_schema"`
	SrcEdge   string `json:"src_edge"`
}

// dataTypeJsonDto is the object form of "data_type". The bare-string form is normalized
// into this shape before decoding.
type dataTypeJsonDto struct {
	Type     string `json:"type"`
	Array    bool   `json:"array"`
	Min      any    `json:"min"`
	Max      any    `json:"max"`
	Scale    uint   `json:"scale"`
	Values   []any  `json:"values"`
	Sanitize string `json:"sanitize"`
	Regex    string `json:"regex"`
}

// ParseModelJson builds a *ModelSchemaBuilder from a model JSON string, validating it
// against the model JSON Schema first.
//
// It panics when the JSON is invalid, matching the rest of the builder API, which treats a
// malformed schema definition as a programming error rather than user input. Use
// ParseModelJsonSafe to handle the errors instead.
func ParseModelJson(modelJson string) *ModelSchemaBuilder {
	builder, clientErrs := ParseModelJsonSafe(modelJson)
	if clientErrs.Count() > 0 {
		panic(errors.Wrap(clientErrs.ToError(), "ParseModelJson"))
	}
	return builder
}

// ParseModelJsonSafe is ParseModelJson without the panic: it returns the validation errors,
// and a nil builder when validation failed.
func ParseModelJsonSafe(modelJson string) (*ModelSchemaBuilder, ft.ClientErrors) {
	clientErrs := dmjson.ValidateSchemaJson(modelJson, dmjson.ModelJsonSchema)
	if clientErrs.Count() > 0 {
		return nil, clientErrs
	}

	var dto modelJsonDto
	if err := cjson.UnmarshalStr(modelJson, &dto); err != nil {
		clientErrs.Append(*ft.NewAnonymousValidationError(dmjson.ErrKeyMalformed, err.Error()))
		return nil, clientErrs
	}

	return buildFromDto(&dto), clientErrs
}

// buildFromDto applies the DTO to a builder in the order the schema semantics require:
// extend_before, then own fields, then extend_after, because field order determines
// column order.
func buildFromDto(dto *modelJsonDto) *ModelSchemaBuilder {
	builder := DefineModel(dto.Name)

	if dto.Label != nil {
		builder.Label(decodeLangJson(dto.Label))
	}
	if dto.Description != nil {
		builder.Description(decodeLangJson(dto.Description))
	}
	if dto.TableName != "" {
		builder.TableName(dto.TableName)
	}
	if dto.ShouldBuildDb {
		builder.ShouldBuildDb()
	}
	if dto.RecordLabelField != "" {
		builder.RecordLabelField(dto.RecordLabelField)
	}
	if dto.RecordSubLabelField != "" {
		builder.RecordSubLabelField(dto.RecordSubLabelField)
	}

	for _, name := range dto.ExtendBefore {
		builder.ExtendByName(name)
	}
	for i := range dto.Fields {
		builder.Field(buildFieldFromDto(&dto.Fields[i]))
	}
	for _, name := range dto.ExtendAfter {
		builder.ExtendByName(name)
	}

	applyConstraints(builder, dto)
	applyEdges(builder, dto)

	return builder
}

func applyConstraints(builder *ModelSchemaBuilder, dto *modelJsonDto) {
	for _, composite := range dto.CompositeUniques {
		builder.CompositeUnique(CompositeUniqueParam{
			IndexName: composite.IndexName,
			Fields:    composite.Fields,
		})
	}
	for _, partial := range dto.PartialUniques {
		builder.PartialUnique(PartialUniqueParam{
			IndexName:     partial.IndexName,
			NotNullFields: partial.NotNullFields,
			NullableField: partial.NullableField,
		})
	}
	for _, index := range dto.SearchIndexes {
		builder.SearchIndexGroup(SearchIndexGroupParam{
			IndexName: index.IndexName,
			Fields:    index.Fields,
		})
	}
	for _, group := range dto.ExclusiveRequiredFields {
		builder.ExclusiveRequiredFields(group...)
	}
}

func applyEdges(builder *ModelSchemaBuilder, dto *modelJsonDto) {
	for i := range dto.EdgesTo {
		builder.EdgeTo(buildRelationFromDto(&dto.EdgesTo[i]))
	}
	for i := range dto.EdgesFrom {
		builder.EdgeFrom(buildRelationFromDto(&dto.EdgesFrom[i]))
	}
}

func buildFieldFromDto(dto *fieldJsonDto) *FieldBuilder {
	field := DefineField().Name(dto.Name)

	// Name() seeds a default label, so only override when the JSON says so.
	if dto.Label != nil {
		field.Label(decodeLangJson(dto.Label))
	}
	if dto.Description != nil {
		field.Description(decodeLangJson(dto.Description))
	}
	if dto.Placeholder != nil {
		field.Placeholder(decodeLangJson(dto.Placeholder))
	}
	field.DataType(decodeDataType(dto.DataType, dto.Name))

	if len(dto.Computed) > 0 {
		applyComputedFromJson(field, dto)
	}

	applyFieldFlags(field, dto)

	if dto.DefaultValue != nil {
		field.Default(dto.DefaultValue)
	}
	if dto.UseTypeDefault {
		field.UseTypeDefault()
	}
	for _, rule := range dto.Rules {
		field.Rule(decodeRule(rule, dto.Name))
	}

	return field
}

// applyComputedFromJson decodes the "computed" block through the parser the computed package
// registered (see computed_hooks.go). It panics on failure, matching the builder API's treatment
// of a malformed schema definition as a programming error.
func applyComputedFromJson(field *FieldBuilder, dto *fieldJsonDto) {
	if computedJsonParser == nil {
		panic(errors.Errorf(
			"field %q declares \"computed\" but the computed package is not linked in; "+
				"import common/dynamicmodel/computed", dto.Name))
	}
	expression, isStored, err := computedJsonParser(dto.Computed, dto.Name)
	if err != nil {
		panic(errors.Wrapf(err, "field %q", dto.Name))
	}
	field.Computed(isStored, expression)
}

// applyFieldFlags applies the boolean options. PrimaryKey, TenantKey and VersioningKey come
// last because they also force required/auto-generated flags and must not be overwritten.
func applyFieldFlags(field *FieldBuilder, dto *fieldJsonDto) {
	if dto.RequiredAlways {
		field.RequiredAlways()
	}
	if dto.RequiredForCreate {
		field.RequiredForCreate()
	}
	if dto.RequiredForUpdate {
		field.RequiredForUpdate()
	}
	if dto.RequiredWith != "" {
		field.RequiredWith(dto.RequiredWith)
	}
	if dto.NoUpdate {
		field.NoUpdate()
	}
	if dto.Unique {
		field.Unique()
	}
	if dto.AutoGenerated {
		field.AutoGenerated()
	}
	if dto.TenantKey {
		field.TenantKey()
	}
	if dto.VersioningKey {
		field.VersioningKey()
	}
	applyPrimaryKey(field, dto)
}

func applyPrimaryKey(field *FieldBuilder, dto *fieldJsonDto) {
	switch primaryKey := dto.PrimaryKey.(type) {
	case nil:
		return
	case bool:
		if primaryKey {
			field.PrimaryKey()
		}
	case map[string]any:
		isAutoGenerated, ok := primaryKey["is_auto_generated"].(bool)
		if !ok {
			field.PrimaryKey()
			return
		}
		field.PrimaryKey(isAutoGenerated)
	default:
		panic(errors.Errorf("field '%s': unsupported primary_key form %T", dto.Name, dto.PrimaryKey))
	}
}

func decodeRule(dto ruleJsonDto, fieldName string) FieldRule {
	switch FieldRuleName(dto.Name) {
	case FieldRuleArrayLengthType:
		return FieldRuleArrayLength(dto.Min, dto.Max)
	default:
		panic(errors.Errorf("field '%s': unsupported rule '%s'", fieldName, dto.Name))
	}
}

func buildRelationFromDto(dto *edgeJsonDto) *RelationBuilder {
	relation := Edge(dto.Edge)

	if dto.Label != nil {
		relation.Label(decodeLangJson(dto.Label))
	}

	if dto.Existing != nil {
		relation.Existing(dto.Existing.SrcSchema, dto.Existing.SrcEdge)
	} else {
		applyRelationType(relation, dto)
	}

	if dto.OnDelete != "" {
		relation.OnDelete(RelationCascade(dto.OnDelete))
	}
	if dto.OnUpdate != "" {
		relation.OnUpdate(RelationCascade(dto.OnUpdate))
	}

	return relation
}

func applyRelationType(relation *RelationBuilder, dto *edgeJsonDto) {
	keyMap := make(DynamicFields, len(dto.KeyMap))
	for srcField, destField := range dto.KeyMap {
		keyMap[srcField] = destField
	}

	switch RelationType(dto.Type) {
	case RelationTypeOneToOne:
		relation.OneToOne(dto.DestSchema, keyMap)
	case RelationTypeOneToMany:
		relation.OneToMany(dto.DestSchema, keyMap)
	case RelationTypeManyToOne:
		relation.ManyToOne(dto.DestSchema, keyMap)
	case RelationTypeManyToMany:
		relation.ManyToMany(dto.PeerSchema, dto.ThroughSchema, dto.SrcFieldPrefix)
	default:
		panic(errors.Errorf("edge '%s': unsupported relation type '%s'", dto.Edge, dto.Type))
	}
}

// decodeLangJson turns a JSON label into a LangJson: a bare string becomes a translation-key
// reference, an object becomes a literal per-language map.
func decodeLangJson(raw any) model.LangJson {
	switch value := raw.(type) {
	case string:
		return model.NewLangJsonRef(value)
	case map[string]any:
		langJson := make(model.LangJson, len(value))
		for langCode, text := range value {
			str, ok := text.(string)
			if !ok {
				panic(errors.Errorf("langJson: value for '%s' must be a string, got %T", langCode, text))
			}
			langJson[langCode] = str
		}
		return langJson
	default:
		panic(errors.Errorf("langJson: unsupported form %T", raw))
	}
}
