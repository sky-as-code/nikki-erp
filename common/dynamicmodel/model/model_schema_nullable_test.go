package model_test

import (
	"context"
	"encoding/json"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	dmodel "github.com/sky-as-code/nikki-erp/common/dynamicmodel/model"
)

func TestColumnNullable_OnlyPrimaryAndTenantKeysAreNotNull(t *testing.T) {
	schema := dmodel.DefineModel("nullable_probe").
		Field(dmodel.DefineField().Name("id").DataType(dmodel.FieldDataTypeUlid()).PrimaryKey()).
		Field(dmodel.DefineField().Name("tenant_id").DataType(dmodel.FieldDataTypeUlid()).TenantKey()).
		Field(dmodel.DefineField().Name("required").DataType(dmodel.FieldDataTypeUlid()).RequiredForCreate()).
		Field(dmodel.DefineField().Name("optional").DataType(dmodel.FieldDataTypeUlid())).
		Build()

	cases := map[string]string{"id": "NOT NULL", "tenant_id": "NOT NULL", "required": "NULL", "optional": "NULL"}
	for name, want := range cases {
		field, ok := schema.Field(name)
		require.True(t, ok, name)
		assert.Equal(t, want, field.ColumnNullable(), name)
		assert.Equal(t, want == "NULL", field.IsNullable(), name)
	}
}

func TestToSimplized_ServiceInjectedReadsAsAutoGenerated(t *testing.T) {
	schema := dmodel.DefineModel("injected_probe").
		Field(dmodel.DefineField().Name("id").DataType(dmodel.FieldDataTypeUlid()).PrimaryKey()).
		Field(dmodel.DefineField().Name("created_by").DataType(dmodel.FieldDataTypeUlid()).
			ServiceInjected(func(context.Context, bool) any { return nil })).
		Build()

	field, ok := schema.Field("created_by")
	require.True(t, ok)
	raw, err := json.Marshal(field.ToSimplizedIn("injected_probe"))
	require.NoError(t, err)
	assert.Contains(t, string(raw), `"is_auto_generated":true`)
}
