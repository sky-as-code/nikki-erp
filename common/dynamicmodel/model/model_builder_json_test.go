func TestParseModelJson_BasicShape(t *testing.T) {
	builder := ParseModelJson(`{
		"name": "test_basic",
		"table_name": "test_basics",
		"should_build_db": true,
		"record_label_field": "name",
		"fields": [
			{"name": "id", "data_type": "ulid", "primary_key": true, "use_type_default": true},
			{"name": "name", "data_type": {"type": "string", "min": 1, "max": 200}, "required_for_create": true}
		]
	}`)
	schema := builder.Build()

	assert.Equal(t, "test_basic", schema.Name())
	assert.Equal(t, "test_basics", schema.TableName())
	assert.Equal(t, []string{"id", "name"}, schema.FieldNames())

	idField, ok := schema.Field("id")
	require.True(t, ok)
	assert.True(t, idField.IsPrimaryKey())
	assert.True(t, idField.IsAutoGenerated(), "primary_key defaults to auto-generated")
}

// The length option is asserted as []int inside validateStringLength, so a raw JSON decode
// (float64) would panic. This guards the concrete-type conversion.
func TestParseModelJson_StringLengthOptionIsIntSlice(t *testing.T) {
	builder := ParseModelJson(`{
		"name": "test_strlen",
		"fields": [{"name": "name", "data_type": {"type": "string", "min": 1, "max": 200}}]
	}`)
	schema := builder.Build()

	field, ok := schema.Field("name")
	require.True(t, ok)

	length := field.DataType().Options()[FieldDataTypeOptLength]
	assert.Equal(t, []int{1, 200}, length)
}

func TestParseModelJson_MatchesGoBuilderForString(t *testing.T) {
	fromGo := DefineModel("test_cmp").
		Field(DefineField().Name("name").DataType(FieldDataTypeString(1, 200))).
		Build()
	fromJson := ParseModelJson(`{
		"name": "test_cmp",
		"fields": [{"name": "name", "data_type": {"type": "string", "min": 1, "max": 200}}]
	}`).Build()

	goField, _ := fromGo.Field("name")
	jsonField, _ := fromJson.Field("name")

	assert.Equal(t, goField.DataType().String(), jsonField.DataType().String())
	assert.Equal(t, goField.DataType().Options(), jsonField.DataType().Options())
	assert.Equal(t, goField.Label(), jsonField.Label(), "Name() seeds the same default label")
}

func TestParseModelJson_DataTypes(t *testing.T) {
	testCases := []struct {
		name     string
		dataType string
		expected FieldDataType
	}{
		{"boolean", `"boolean"`, FieldDataTypeBoolean()},
		{"ulid", `"ulid"`, FieldDataTypeUlid()},
		{"email", `"email"`, FieldDataTypeEmail()},
		{"etag", `"etag"`, FieldDataTypeEtag()},
		{"slug", `"slug"`, FieldDataTypeSlug()},
		{"datetime", `"datetime"`, FieldDataTypeDateTime()},
		{"int32", `{"type":"int32","min":0,"max":100}`, FieldDataTypeInt32(0, 100)},
		{"int64", `{"type":"int64","min":0,"max":900}`, FieldDataTypeInt64(0, 900)},
		{"decimal", `{"type":"decimal","min":"0","max":"99.9","scale":2}`, FieldDataTypeDecimal("0", "99.9", 2)},
		{"langjson", `{"type":"langjson","min":1,"max":200}`, FieldDataTypeLangJson(1, 200)},
		{"enumString", `{"type":"enum_string","values":["a","b"]}`, FieldDataTypeEnumString([]string{"a", "b"})},
		{"enumInt32", `{"type":"enum_int32","values":[1,2]}`, FieldDataTypeEnumInt32([]int32{1, 2})},
		{"ulidArray", `{"type":"ulid","array":true}`, FieldDataTypeUlid().ArrayType()},
		{"secret", `{"type":"secret","min":1,"max":50}`, FieldDataTypeSecret(1, 50)},
	}

	for _, testCase := range testCases {
		t.Run(testCase.name, func(t *testing.T) {
			schema := ParseModelJson(`{
				"name": "test_dt",
				"fields": [{"name": "f", "data_type": ` + testCase.dataType + `}]
			}`).Build()

			field, ok := schema.Field("f")
			require.True(t, ok)
			assert.Equal(t, testCase.expected.String(), field.DataType().String())
			assert.Equal(t, testCase.expected.IsArray(), field.DataType().IsArray())
			assert.Equal(t, testCase.expected.Options(), field.DataType().Options())
		})
	}
}

