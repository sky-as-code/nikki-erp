func TestGetField_MutatesInPlace(t *testing.T) {
	builder := ParseModelJson(`{
		"name": "test_getfield",
		"fields": [{"name": "created_by", "data_type": "ulid"}]
	}`)

	assert.True(t, builder.HasField("created_by"))
	assert.False(t, builder.HasField("nope"))

	builder.GetField("created_by").ServiceInjected(func(ctx context.Context, forEdit bool) any {
		return "injected"
	})

	field, ok := builder.Build().Field("created_by")
	require.True(t, ok)
	assert.True(t, field.IsServiceInjected(), "GetField must mutate the already-added field")
}

func TestGetField_PanicsWhenAbsent(t *testing.T) {
	builder := ParseModelJson(`{"name": "test_getfield_missing"}`)

	assert.Panics(t, func() { builder.GetField("nope") })
}

// registerTestBaseBuilder registers a builder factory and removes it when the test ends,
// so the package-level registry does not leak between tests.
func registerTestBaseBuilder(t *testing.T, name string, factory func() *ModelSchemaBuilder) {
	t.Helper()
	require.NoError(t, RegisterSchemaBuilderFn(name, factory))
	t.Cleanup(func() {
		builderRegistry.mu.Lock()
		delete(builderRegistry.factories, name)
		builderRegistry.mu.Unlock()
	})
}
