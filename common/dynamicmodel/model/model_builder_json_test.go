func TestParseModelJson_Edges(t *testing.T) {
	schema := ParseModelJson(`{
		"name": "test_edges",
		"fields": [{"name": "owner_id", "data_type": "ulid"}],
		"edges_to": [
			{
				"edge": "owner",
				"label": {"en-US": "Owner"},
				"type": "many:one",
				"dest_schema": "iam_user",
				"key_map": {"owner_id": "id"},
				"on_delete": "CASCADE"
			},
			{
				"edge": "members",
				"type": "many:many",
				"peer_schema": "iam_user",
				"through_schema": "iam_group_user_rel",
				"src_field_prefix": "group"
			}
		],
		"edges_from": [
			{"edge": "own_roles", "existing": {"src_schema": "iam_role", "src_edge": "owner_group"}}
		]
	}`).Build()

	toRelations := schema.ToRelations()
	require.Len(t, toRelations, 2)
	assert.Equal(t, "owner", toRelations[0].Edge)
	assert.Equal(t, RelationTypeManyToOne, toRelations[0].RelationType)
	assert.Equal(t, RelationCascadeCascade, toRelations[0].OnDelete)
	assert.Equal(t, RelationTypeManyToMany, toRelations[1].RelationType)
	assert.Equal(t, "iam_group_user_rel", toRelations[1].M2mThroughSchemaName)

	fromRelations := schema.FromRelations()
	require.Len(t, fromRelations, 1)
	assert.Equal(t, "own_roles", fromRelations[0].Edge)

	// EdgeTo adds an implicit virtual field per edge.
	_, hasOwnerField := schema.Field("owner")
	assert.True(t, hasOwnerField)
	_, hasMembersField := schema.Field("members")
	assert.True(t, hasMembersField)
}

func TestParseModelJson_Constraints(t *testing.T) {
	schema := ParseModelJson(`{
		"name": "test_constraints",
		"fields": [
			{"name": "name", "data_type": "boolean"},
			{"name": "org_id", "data_type": "ulid"},
			{"name": "user_id", "data_type": "ulid"}
		],
		"composite_uniques": [{"index_name": "tc_name_org", "fields": ["name", "org_id"]}],
		"partial_uniques": [{"not_null_fields": ["name"], "nullable_field": "org_id"}],
		"search_indexes": [{"fields": ["name"]}],
		"exclusive_required_fields": [["org_id", "user_id"]]
	}`).Build()

	assert.Equal(t,
		[]CompositeUniqueParam{{IndexName: "tc_name_org", Fields: []string{"name", "org_id"}}},
		schema.CompositeUniques())
	assert.Len(t, schema.PartialUniques(), 1)
	assert.Len(t, schema.SearchIndexGroups(), 1)
}

