func TestParseModelJson_ExtendOrderingPutsExtendBeforeFirst(t *testing.T) {
	registerTestBaseBuilder(t, "test.base.id", func() *ModelSchemaBuilder {
		return DefineModel("test.base.id").
			Field(DefineField().Name("id").DataType(FieldDataTypeUlid()).PrimaryKey())
	})
	registerTestBaseBuilder(t, "test.base.archived", func() *ModelSchemaBuilder {
		return DefineModel("test.base.archived").
			Field(DefineField().Name("is_archived").DataType(FieldDataTypeBoolean()))
	})

	schema := ParseModelJson(`{
		"name": "test_extend",
		"extend_before": ["test.base.id"],
		"fields": [{"name": "name", "data_type": "boolean"}],
		"extend_after": ["test.base.archived"]
	}`).Build()

	assert.Equal(t, []string{"id", "name", "is_archived"}, schema.FieldNames())
}

